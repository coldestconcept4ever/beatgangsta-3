const langs = ['en', 'es', 'fr', 'ru', 'pt'];

for (const lang of langs) {
  // Matches `en: { translation: {` or `"en": { "translation": {`
  const regex = new RegExp(`(["']?${lang}["']?:\\s*\\{\\s*["']?translation["']?:\\s*\\{)([\\s\\S]*?)(\\}\\s*\\})`, 'g');
  content = content.replace(regex, (match, p1, p2, p3) => {
    let newP2 = p2;
    for (const [key, value] of Object.entries(keysToAdd[lang])) {
      if (!newP2.includes(`"${key}":`)) {
        newP2 = newP2.replace(/,\s*$/, '') + `,\n      "${key}": "${value}"`;
      } else {
        // Replace existing value to ensure consistency
        const keyRegex = new RegExp(`"${key}":\\s*".*?"`, 'g');
        newP2 = newP2.replace(keyRegex, `"${key}": "${value}"`);
      }
    }
    return p1 + newP2 + p3;
  });
}

fs.writeFileSync(i18nPath, content);
